#!/usr/bin/env python3
"""Build the 凡人女修 slideshow wallpaper assets.

Reads a folder of source images, writes downsampled JPEGs with ASCII names into
``Wallpapers/凡人女修/images/`` and emits ``manifest.js`` with the Chinese
character names. Only ``images/`` and ``manifest.js`` are generated; the
hand-written wallpaper sources (project.json, index.html, style.css, app.js)
are never touched.

Rationale for downsampling: source frames are 5504x3072 (~64 MB each once
decoded). Two cross-fading layers per display would cost several hundred MB.
2560 px wide JPEGs keep full-screen quality at roughly 1/3 the file size and
1/4 the decoded footprint.

Usage:
    python3 tools/build-slideshow.py
    python3 tools/build-slideshow.py --source "/path/to/图" --width 3200 --quality 88
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
# No absolute default on purpose: the image folder is local to each machine.
# Pass it explicitly with --source.
DEFAULT_SOURCE = Path("图")
DEFAULT_OUTPUT = PROJECT_ROOT / "Wallpapers" / "凡人女修"
IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".webp", ".heic", ".tiff"}
NUMBER_WORDS = {2: "二", 3: "三", 4: "四", 5: "五", 6: "六", 7: "七", 8: "八", 9: "九", 10: "十"}


def display_names(stems: list[str]) -> list[str]:
    """Strip trailing ' (2)' / '（1）' suffixes and disambiguate duplicates.

    Within a duplicate group the un-suffixed file is always the primary name,
    even when a lexicographically earlier ' (2)' file precedes it on disk.
    """
    suffix_re = re.compile(r"\s*[（(]\s*\d+\s*[)）]\s*$")
    bases = [suffix_re.sub("", s).strip() or s for s in stems]
    has_suffix = [bool(suffix_re.search(s)) for s in stems]

    groups: dict[str, list[int]] = {}
    for i, base in enumerate(bases):
        groups.setdefault(base, []).append(i)

    result = [""] * len(stems)
    for base, indexes in groups.items():
        ordered = sorted(indexes, key=lambda i: (has_suffix[i], i))
        for rank, i in enumerate(ordered):
            if rank == 0:
                result[i] = base
            else:
                ordinal = rank + 1
                result[i] = f"{base} · 其{NUMBER_WORDS.get(ordinal, ordinal)}"
    return result


def build(source: Path, output: Path, width: int, quality: int) -> int:
    if not source.is_dir():
        print(f"error: source directory not found: {source}", file=sys.stderr)
        return 1

    files = sorted(
        (p for p in source.iterdir() if p.is_file() and p.suffix.lower() in IMAGE_SUFFIXES),
        key=lambda p: p.name,
    )
    if not files:
        print(f"error: no images in {source}", file=sys.stderr)
        return 1

    images_dir = output / "images"
    images_dir.mkdir(parents=True, exist_ok=True)
    names = display_names([p.stem for p in files])

    entries = []
    total_bytes = 0
    for index, (src, name) in enumerate(zip(files, names), start=1):
        filename = f"{index:03d}.jpg"
        dst = images_dir / filename
        command = [
            "sips", "-Z", str(width),
            "--setProperty", "formatOptions", str(quality),
            str(src), "--out", str(dst),
        ]
        done = subprocess.run(command, capture_output=True, text=True)
        if done.returncode != 0:
            print(f"error: sips failed on {src.name}: {done.stderr.strip()}", file=sys.stderr)
            return 1
        total_bytes += dst.stat().st_size
        entries.append({"file": f"images/{filename}", "name": name})
        print(f"  [{index:02d}/{len(files):02d}] {src.name} -> {filename}  ({name})")

    # Remove stale generated frames when the source folder shrinks.
    expected = {f"{i:03d}.jpg" for i in range(1, len(files) + 1)}
    for stale in images_dir.glob("???.jpg"):
        if stale.name not in expected:
            stale.unlink()

    manifest = (
        "/* Generated by tools/build-slideshow.py — do not edit by hand. */\n"
        "window.__FM_IMAGES = "
        + json.dumps(entries, ensure_ascii=False, indent=2)
        + ";\n"
    )
    (output / "manifest.js").write_text(manifest, encoding="utf-8")

    print(f"\n{len(entries)} frames, {total_bytes / 1048576:.1f} MB total, "
          f"max width {width}px, JPEG quality {quality}")
    print(f"manifest: {output / 'manifest.js'}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="folder with source images")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="wallpaper directory")
    parser.add_argument("--width", type=int, default=2560, help="maximum edge in pixels (default 2560)")
    parser.add_argument("--quality", type=int, default=85, help="JPEG quality 1-100 (default 85)")
    args = parser.parse_args()
    if not 1 <= args.quality <= 100 or args.width < 640:
        print("error: --quality must be 1-100 and --width >= 640", file=sys.stderr)
        return 2
    return build(args.source.expanduser().resolve(), args.output.expanduser().resolve(),
                 args.width, args.quality)


if __name__ == "__main__":
    raise SystemExit(main())
